import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import * as fontkit from "fontkit";
import subsetFont from "subset-font";

async function files(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  return (await Promise.all(entries.map((entry) => entry.isDirectory() ? files(join(dir, entry.name)) : join(dir, entry.name)))).flat();
}

const original = await readFile("assets-source/fonts/SmileySans-Oblique.woff2");
const characters = fontkit.create(original).characterSet.sort((a, b) => a - b);
const common = new Set(Array.from({ length: 0x250 }, (_, code) => code));
for (const file of (await files("src")).filter((file) => /\.tsx?$/.test(file))) {
  const text = (await readFile(file, "utf8")).replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/[^\n]*/g, "");
  for (const char of text) common.add(char.codePointAt(0));
}
for (const file of (await files("public/content")).filter((file) => /stories[\\/]\d+\.md$/.test(file))) {
  const title = (await readFile(file, "utf8")).split("\n")[0];
  for (const char of title) common.add(char.codePointAt(0));
}
const commonCodes = characters.filter((code) => common.has(code));
const remaining = characters.filter((code) => !common.has(code));
const groups = [{ name: "common", codes: commonCodes }];
for (let index = 0; index < remaining.length; index += 200) groups.push({ name: String(index / 200 + 1).padStart(2, "0"), codes: remaining.slice(index, index + 200) });

function ranges(codes) {
  const groups = [];
  for (const code of codes) {
    const last = groups.at(-1);
    if (last && code === last[1] + 1) last[1] = code;
    else groups.push([code, code]);
  }
  return groups.map(([start, end]) => `U+${start.toString(16)}${start === end ? "" : `-${end.toString(16)}`}`).join(",");
}

await mkdir("src/assets/fonts", { recursive: true });
const css = ["/* Generated by npm run optimize-font; every original character remains available. */"];
for (const group of groups) {
  const filename = `smiley-${group.name}.woff2`;
  const subset = await subsetFont(original, String.fromCodePoint(...group.codes), { targetFormat: "woff2", preserveNameIds: [0, 7, 13, 14] });
  await writeFile(join("src/assets/fonts", filename), subset);
  css.push(`@font-face { font-family: "Smiley Sans"; font-style: normal; font-weight: 400; font-display: swap; src: url("../assets/fonts/${filename}") format("woff2"); unicode-range: ${ranges(group.codes)}; }`);
  console.log(`${filename}: ${group.codes.length} characters, ${subset.length} bytes`);
}
await writeFile("src/styles/smiley-fonts.css", css.join("\n") + "\n");
await rm("src/assets/fonts/SmileySans-Oblique.woff2", { force: true });
